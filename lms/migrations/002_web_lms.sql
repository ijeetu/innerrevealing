ALTER TABLE ir_users MODIFY role ENUM('student','admin','superadmin') NOT NULL DEFAULT 'student';

CREATE TABLE IF NOT EXISTS ir_media (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 storage_name VARCHAR(100) NOT NULL UNIQUE,
 original_name VARCHAR(255) NOT NULL,
 mime_type VARCHAR(100) NOT NULL,
 byte_size BIGINT UNSIGNED NOT NULL,
 kind ENUM('image','video','audio','document') NOT NULL,
 is_public BOOLEAN NOT NULL DEFAULT FALSE,
 uploaded_by BIGINT UNSIGNED NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT ir_media_uploader FOREIGN KEY(uploaded_by) REFERENCES ir_users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS ir_chapters (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 course_id BIGINT UNSIGNED NOT NULL,
 title VARCHAR(200) NOT NULL,
 position INT UNSIGNED NOT NULL DEFAULT 0,
 CONSTRAINT ir_chapters_course FOREIGN KEY(course_id) REFERENCES ir_courses(id) ON DELETE CASCADE,
 KEY ir_chapters_order(course_id,position)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS ir_lessons (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 course_id BIGINT UNSIGNED NOT NULL,
 chapter_id BIGINT UNSIGNED NOT NULL,
 title VARCHAR(200) NOT NULL,
 type ENUM('video','audio','pdf','text') NOT NULL,
 content LONGTEXT NULL,
 media_id BIGINT UNSIGNED NULL,
 external_url VARCHAR(2000) NULL,
 duration_seconds INT UNSIGNED NOT NULL DEFAULT 0,
 position INT UNSIGNED NOT NULL DEFAULT 0,
 is_preview BOOLEAN NOT NULL DEFAULT FALSE,
 is_published BOOLEAN NOT NULL DEFAULT TRUE,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT ir_lessons_course FOREIGN KEY(course_id) REFERENCES ir_courses(id) ON DELETE CASCADE,
 CONSTRAINT ir_lessons_chapter FOREIGN KEY(chapter_id) REFERENCES ir_chapters(id) ON DELETE CASCADE,
 CONSTRAINT ir_lessons_media FOREIGN KEY(media_id) REFERENCES ir_media(id) ON DELETE RESTRICT,
 KEY ir_lessons_order(chapter_id,position)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS ir_orders (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL,
 order_number VARCHAR(40) NOT NULL UNIQUE,
 amount DECIMAL(10,2) NOT NULL,
 currency CHAR(3) NOT NULL DEFAULT 'INR',
 status ENUM('pending','awaiting_review','paid','rejected','cancelled','refunded') NOT NULL DEFAULT 'pending',
 payment_method ENUM('free','manual','razorpay') NOT NULL,
 payment_reference VARCHAR(200) NULL,
 razorpay_order_id VARCHAR(100) NULL UNIQUE,
 razorpay_payment_id VARCHAR(100) NULL UNIQUE,
 notes TEXT NULL,
 reviewed_by BIGINT UNSIGNED NULL,
 reviewed_at DATETIME NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT ir_orders_user FOREIGN KEY(user_id) REFERENCES ir_users(id) ON DELETE RESTRICT,
 CONSTRAINT ir_orders_reviewer FOREIGN KEY(reviewed_by) REFERENCES ir_users(id) ON DELETE SET NULL,
 KEY ir_orders_status(status,created_at),
 CONSTRAINT ir_orders_amount CHECK(amount >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS ir_order_items (
 order_id BIGINT UNSIGNED NOT NULL,
 course_id BIGINT UNSIGNED NOT NULL,
 title_snapshot VARCHAR(200) NOT NULL,
 amount DECIMAL(10,2) NOT NULL,
 PRIMARY KEY(order_id,course_id),
 CONSTRAINT ir_order_items_order FOREIGN KEY(order_id) REFERENCES ir_orders(id) ON DELETE CASCADE,
 CONSTRAINT ir_order_items_course FOREIGN KEY(course_id) REFERENCES ir_courses(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS ir_enrollments (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL,
 course_id BIGINT UNSIGNED NOT NULL,
 status ENUM('active','revoked') NOT NULL DEFAULT 'active',
 source ENUM('free','manual','razorpay','admin') NOT NULL,
 order_id BIGINT UNSIGNED NULL,
 granted_by BIGINT UNSIGNED NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY ir_enrollment_user_course(user_id,course_id),
 CONSTRAINT ir_enrollments_user FOREIGN KEY(user_id) REFERENCES ir_users(id) ON DELETE CASCADE,
 CONSTRAINT ir_enrollments_course FOREIGN KEY(course_id) REFERENCES ir_courses(id) ON DELETE CASCADE,
 CONSTRAINT ir_enrollments_order FOREIGN KEY(order_id) REFERENCES ir_orders(id) ON DELETE SET NULL,
 CONSTRAINT ir_enrollments_granter FOREIGN KEY(granted_by) REFERENCES ir_users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS ir_cart (
 user_id BIGINT UNSIGNED NOT NULL,
 course_id BIGINT UNSIGNED NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(user_id,course_id),
 CONSTRAINT ir_cart_user FOREIGN KEY(user_id) REFERENCES ir_users(id) ON DELETE CASCADE,
 CONSTRAINT ir_cart_course FOREIGN KEY(course_id) REFERENCES ir_courses(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS ir_progress (
 user_id BIGINT UNSIGNED NOT NULL,
 lesson_id BIGINT UNSIGNED NOT NULL,
 completed BOOLEAN NOT NULL DEFAULT FALSE,
